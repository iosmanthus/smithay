/// Events that are generated by interactions of the clients with the data device.
pub trait SelectionHandler: Sized + SeatHandler {
    /// UserData attached to server-side selections.
    type SelectionUserData: Clone + Send + Sync + 'static;

    /// A client has set the selection
    #[allow(unused_variables)]
    fn new_selection(&mut self, ty: SelectionTarget, source: Option<SelectionSource>, seat: Seat<Self>) {}

    /// A client requested to read the server-set selection.
    ///
    /// * `mime_type` - the requested mime type
    /// * `fd` - the fd to write into
    #[allow(unused_variables)]
    fn send_selection(
        &mut self,
        ty: SelectionTarget,
        mime_type: String,
        fd: OwnedFd,
        seat: Seat<Self>,
        user_data: &Self::SelectionUserData,
    ) {
    }

    /// A Wayland client asked to read a selection: a `receive` request on a clipboard, primary
    /// selection or data-control offer, for a mime type that the offer announced. Every such read
    /// comes here; one that cannot (its seat is gone) is refused.
    ///
    /// The default serves the read as smithay always did: the client source writes the data into
    /// `fd`, or [`send_selection`](Self::send_selection) does for a selection that the compositor
    /// set. A compositor that overrides this method can see who reads which selection, through
    /// which kind of device, and whether the offer is still the current selection; it can then
    /// serve the read with [`SelectionRead::forward`], refuse it by dropping `fd`, or write other
    /// data into `fd`.
    fn receive_selection(
        &mut self,
        read: SelectionRead<Self::SelectionUserData>,
        fd: OwnedFd,
        seat: Seat<Self>,
    ) {
        read.forward(self, fd, seat);
    }
}

/// A client's request to read a selection, given to [`SelectionHandler::receive_selection`].
#[derive(Debug)]
#[non_exhaustive]
pub struct SelectionRead<U> {
    /// The selection that is read.
    pub target: SelectionTarget,
    /// The kind of device the offer was made on.
    pub device_kind: SelectionDeviceKind,
    /// The client that reads.
    pub reader: Client,
    /// Where the data comes from.
    pub source: SelectionReadSource<U>,
    /// The requested mime type, one that the offer announced.
    pub mime_type: String,
    /// The number of changes of the selection of [`target`](Self::target) when the offer was made.
    /// Reads with the same target and generation read the same selection.
    pub generation: u64,
    /// Whether the offer still is the current selection of its target. A client can keep an
    /// offer of an older selection and read it later, while its source is alive.
    pub current: bool,
}

/// The source of the data of a [`SelectionRead`].
#[derive(Debug)]
pub enum SelectionReadSource<U> {
    /// A client's selection source.
    Client(SelectionSource),
    /// A selection that the compositor set, with its user data.
    Compositor(U),
}

impl<U> SelectionRead<U> {
    /// Serve the read as smithay does by default: the client source writes the data into `fd`, or
    /// [`SelectionHandler::send_selection`] does for a selection that the compositor set.
    pub fn forward<D>(self, handler: &mut D, fd: OwnedFd, seat: Seat<D>)
    where
        D: SelectionHandler<SelectionUserData = U>,
    {
        match self.source {
            SelectionReadSource::Client(source) => source.send(self.mime_type, fd),
            SelectionReadSource::Compositor(user_data) => {
                handler.send_selection(self.target, self.mime_type, fd, seat, &user_data)
            }
        }
    }
}

/// The target for the selection request.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SelectionTarget {
    /// The target for the request is primary selection.
    Primary,
    /// The target for the request is clipboard selection.
    Clipboard,
}

pub(crate) mod private {
    /// `selection_dispatch!(self; Enum(foo) => foo.something())`
    /// expands to the equivalent of
    /// ```ignore
    /// match self {
    ///    Enum::DataDevice(foo) => foo.something(),
    ///    Enum::Primary(foo) => foo.something(),
    ///    Enum::WlrDataControl(foo) => foo.something(),
    ///    Enum::ExtDataControl(foo) => foo.something(),
    /// }
    /// ```
    ///
    /// And `selection_dispatch!(self, other; Enum(foo), EnumNext(zoo) => foo.something(zoo))` expands
    /// to the equivalent of
    /// ```ignore
    /// match (self, other) {
    ///    (Enum::DataDevice(foo), EnumNext::DataDevice(zoo))  => foo.something(zoo),
    ///    (Enum::Primary(foo), EnumNext::Primary(zoo))  => foo.something(zoo),
    ///    (Enum::WlrDataControl(foo), EnumNext::WlrDataControl(zoo))  => foo.something(zoo),
    ///    (Enum::ExtDataControl(foo), EnumNext::ExtDataControl(zoo))  => foo.something(zoo),
    ///    _ => unreachable!(),
    /// }
    /// ```
    ///
    /// The result can be converted to another enum by adding `; as AnotherEnum`
    macro_rules! selection_dispatch {
        ($what:ident; $enum:ident ( $($c1:tt)* ) => $x:expr) => {
            match $what {
                $enum::DataDevice($($c1)*) => $x,
                $enum::Primary($($c1)*) => $x,
                $enum::WlrDataControl($($c1)*) => $x,
                $enum::ExtDataControl($($c1)*) => $x,
            }
        };
        ($what:ident$(, $what_next:ident)+; $enum:ident ( $($c1:tt)*) $(, $enum_next:ident ( $($c2:tt)* ) )+ => $x:expr) => {
            match ($what$(, $what_next)*) {
                ($enum::DataDevice($($c1)*)$(, $enum_next::DataDevice($($c2)*))*) => $x,
                ($enum::Primary($($c1)*)$(, $enum_next::Primary($($c2)*))*) => $x,
                ($enum::WlrDataControl($($c1)*)$(, $enum_next::WlrDataControl($($c2)*))*) => $x,
                ($enum::ExtDataControl($($c1)*)$(, $enum_next::ExtDataControl($($c2)*))*) => $x,
                _ => unreachable!(),
            }
        };
    }

    pub(crate) use selection_dispatch;
}
